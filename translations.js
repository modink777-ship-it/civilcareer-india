function ensureTamilOption() {
  const group = document.querySelector(".lang-toggle");
  if (group && !group.querySelector('[data-lang="ta"]')) {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "lang-option";
    button.dataset.lang = "ta";
    button.textContent = "த";
    button.setAttribute("aria-label", "தமிழ்");
    group.appendChild(button);
  }
  const mobileNav = document.querySelector("#mainNav .mobile-nav-grid");
  if (mobileNav && !mobileNav.querySelector('a[href="/about"]')) {
    const about = document.createElement("a");
    about.href = "/about";
    about.dataset.i18n = "nav_about";
    about.textContent = window.t ? window.t("nav_about") : "About";
    mobileNav.appendChild(about);
  }
}

window.t = function (key) {
  let lang = "en";
  try { lang = localStorage.getItem("cc_lang") || "en"; } catch (_) {}
  return (TRANSLATIONS[lang] && TRANSLATIONS[lang][key]) || TRANSLATIONS.en[key] || key;
};

window.applyLanguage = function (requestedLang) {
  const lang = Object.prototype.hasOwnProperty.call(TRANSLATIONS, requestedLang) ? requestedLang : "en";
  try { localStorage.setItem("cc_lang", lang); } catch (_) {}
  document.documentElement.lang = lang;
  ensureTamilOption();

  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const value = window.t(el.dataset.i18n);
    if (el.matches("input, textarea")) el.placeholder = value;
    else el.textContent = value;
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    el.placeholder = window.t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll("[data-i18n-aria-label]").forEach(function (el) {
    el.setAttribute("aria-label", window.t(el.dataset.i18nAriaLabel));
  });
  SEMANTIC_TRANSLATIONS.forEach(function ([selector, key]) {
    document.querySelectorAll(selector).forEach(function (el) {
      if (!el.hasAttribute("data-i18n")) el.textContent = window.t(key);
    });
  });
  document.querySelectorAll(".lang-option").forEach(function (button) {
    const active = button.dataset.lang === lang;
    button.classList.toggle("active", active);
    button.setAttribute("aria-pressed", String(active));
    button.onclick = function () { window.applyLanguage(button.dataset.lang); };
  });
  const languageGroup = document.querySelector(".lang-toggle");
  if (languageGroup) languageGroup.setAttribute("aria-label", window.t("language_label"));
  const searchButton = document.getElementById("searchOpen");
  if (searchButton) {
    searchButton.textContent = window.t("search_open");
    searchButton.setAttribute("aria-label", window.t("search_open"));
  }
  const menuButton = document.getElementById("menuBtn");
  if (menuButton) menuButton.setAttribute("aria-label", window.t(menuButton.getAttribute("aria-expanded") === "true" ? "close_navigation" : "open_navigation"));
  const roleSearch = document.getElementById("ccSearchRoles");
  if (roleSearch) roleSearch.placeholder = window.t("search_roles_placeholder");
  const citySearch = document.getElementById("ccSearchCities");
  if (citySearch) citySearch.placeholder = window.t("search_locations_placeholder");
  document.dispatchEvent(new CustomEvent("civilcareer:languagechange", { detail: { lang: lang } }));
};

document.addEventListener("DOMContentLoaded", function () {
  let lang = "en";
  try { lang = localStorage.getItem("cc_lang") || "en"; } catch (_) {}
  window.applyLanguage(lang);
});
